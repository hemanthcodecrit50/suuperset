"""Portfolio (verified projects, skills, achievements) CRUD.

This is the evidence base the resume engine is grounded in. Every item should be
something the user can point to; nothing here is generated by a model.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import PortfolioItem

logger = logging.getLogger(__name__)

STATUSES = ("planned", "in_progress", "implemented", "completed")


@dataclass
class PortfolioSummary:
    items: list[PortfolioItem]
    technologies: list[str]


def _clean_list(value) -> list[str]:
    if value is None:
        return []
    if isinstance(value, str):
        return [part.strip() for part in value.replace(",", "\n").split("\n") if part.strip()]
    return [str(v).strip() for v in value if str(v).strip()]


def list_items(session: Session) -> list[PortfolioItem]:
    return list(session.scalars(select(PortfolioItem).order_by(PortfolioItem.id.desc())).all())


def summary(session: Session) -> PortfolioSummary:
    items = list_items(session)
    technologies: list[str] = []
    for item in items:
        for tech in item.technologies or []:
            if tech not in technologies:
                technologies.append(tech)
    return PortfolioSummary(items=items, technologies=technologies)


def add_item(
    session: Session,
    *,
    name: str,
    description: str | None = None,
    technologies=None,
    achievements=None,
    evidence_url: str | None = None,
    status: str = "implemented",
) -> PortfolioItem:
    if status not in STATUSES:
        raise ValueError(f"Unknown status {status!r}. Valid: {', '.join(STATUSES)}")
    item = PortfolioItem(
        name=name.strip(),
        description=(description or "").strip() or None,
        technologies=_clean_list(technologies),
        achievements=_clean_list(achievements),
        evidence_url=(evidence_url or "").strip() or None,
        status=status,
    )
    session.add(item)
    session.flush()
    return item


def update_item(session: Session, item_id: int, **fields) -> PortfolioItem | None:
    item = session.get(PortfolioItem, item_id)
    if item is None:
        return None
    for key, value in fields.items():
        if value is None:
            continue
        if key in ("technologies", "achievements"):
            value = _clean_list(value)
        if key == "status" and value not in STATUSES:
            raise ValueError(f"Unknown status {value!r}")
        setattr(item, key, value)
    session.flush()
    return item


def delete_item(session: Session, item_id: int) -> bool:
    item = session.get(PortfolioItem, item_id)
    if item is None:
        return False
    session.delete(item)
    session.flush()
    return True